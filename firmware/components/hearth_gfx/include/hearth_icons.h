inline const uint16_t* HearthWeatherIcon(const char* kind) {
    if (kind == nullptr || kind[0] == '\0') {
        return kIconSun;
    }
    // Hub sends a short token: rain, storm, snow, fog, cloud, partly, sun.
    if (kind[0] == 'r') {
        return kIconRain;
    }
    if (kind[0] == 't' || (kind[0] == 's' && kind[1] == 't')) {
        return kIconStorm;
    }
    if (kind[0] == 's' && kind[1] == 'n') {
        return kIconSnow;
    }
    if (kind[0] == 'f') {
        return kIconFog;
    }
    if (kind[0] == 'c') {
        return kIconCloud;
    }
    if (kind[0] == 'p') {
        return kIconPartly;
    }
    return kIconSun;
}

